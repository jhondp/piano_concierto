// Merges data/*.json into assets/data.js (a plain script so the site also works from file://).
// Usage: node tools/build-data.mjs
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { buildRoadmap, buildSessions, guideId } from "./plan.mjs";

const root = new URL("../", import.meta.url);
const read = f => JSON.parse(readFileSync(new URL("data/" + f, root), "utf8"));

const concert = read("concert.json");
const hanon = read("hanon.json").exercises;
const czerny = read("czerny.json").exercises;
const practice = read("practice.json").strategies;
const guide = read("exercise-guide.json");
// Detailed per-exercise study guides, keyed by exercise number.
const byNo = f => Object.fromEntries(read(f).exercises.map(e => [e.no, e]));
const hanonDetail = byNo("hanon-detail.json"), czernyDetail = byNo("czerny-detail.json");
const pieces = readdirSync(new URL("data/", root))
  .filter(f => /^pieces-.*\.json$/.test(f)).flatMap(read)
  .sort((a, b) => a.id.localeCompare(b.id));

if (pieces.length !== 16) console.warn(`warning: expected 16 pieces, found ${pieces.length}`);

const roadmap = buildRoadmap(pieces, { start: concert.start, concert: concert.date, rehearsalWeeks: concert.rehearsalWeeks, polishWeeks: concert.polishWeeks, bufferWeeks: concert.bufferWeeks, route: concert.route });
for (const p of pieces) {
  const slot = roadmap.items.find(i => i.id === p.id);
  p.plan = slot;
  p.sessions = buildSessions(p, hanon, czerny, (slot.order - 1) * 2, practice);
  for (const s of p.sessions) {
    if (s.warmup) s.warmup.guide = guideId(guide, "hanon", s.warmup.no);
    if (s.hanon) s.hanon.guide = guideId(guide, "hanon", s.hanon.no);
    if (s.czerny) s.czerny.guide = guideId(guide, "czerny", s.czerny.no);
  }
}

const out = `// Generated by tools/build-data.mjs. Edit data/*.json and rebuild.\nwindow.DATA = ${JSON.stringify({ concert, roadmap, pieces, hanon, czerny, practice, guide, hanonDetail, czernyDetail }, null, 1)};\n`;
writeFileSync(new URL("assets/data.js", root), out);
console.log(`assets/data.js: ${pieces.length} pieces, ${pieces.reduce((s, p) => s + p.sessions.length, 0)} sessions`);

// Cache-busting: stamp each local asset reference in the pages with a hash of its contents,
// so phones fetch new versions instead of reusing cached ones.
const pages = readdirSync(root).filter(f => f.endsWith(".html"));
for (const page of pages) {
  const url = new URL(page, root), html = readFileSync(url, "utf8");
  const next = html.replace(/(src|href)="(assets\/[^"?]+\.(?:js|css))(?:\?v=[0-9a-f]+)?"/g, (_, attr, path) =>
    `${attr}="${path}?v=${createHash("sha1").update(readFileSync(new URL(path, root))).digest("hex").slice(0, 8)}"`);
  if (next !== html) writeFileSync(url, next);
}
console.log(`stamped asset versions in ${pages.length} pages`);
