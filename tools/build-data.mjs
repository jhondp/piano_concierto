// Merges data/*.json into assets/data.js (a plain script so the site also works from file://).
// Usage: node tools/build-data.mjs
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { buildRoadmap, buildSessions } from "./plan.mjs";

const root = new URL("../", import.meta.url);
const read = f => JSON.parse(readFileSync(new URL("data/" + f, root), "utf8"));

const concert = read("concert.json");
const hanon = read("hanon.json").exercises;
const czerny = read("czerny.json").exercises;
const practice = read("practice.json").strategies;
const pieces = readdirSync(new URL("data/", root))
  .filter(f => /^pieces-.*\.json$/.test(f)).flatMap(read)
  .sort((a, b) => a.id.localeCompare(b.id));

if (pieces.length !== 16) console.warn(`warning: expected 16 pieces, found ${pieces.length}`);

const roadmap = buildRoadmap(pieces, { start: concert.start, concert: concert.date, rehearsalWeeks: concert.rehearsalWeeks, polishWeeks: concert.polishWeeks, bufferWeeks: concert.bufferWeeks, route: concert.route });
for (const p of pieces) {
  const slot = roadmap.items.find(i => i.id === p.id);
  p.plan = slot;
  p.sessions = buildSessions(p, hanon, czerny, (slot.order - 1) * 2, practice);
}

const out = `// Generated by tools/build-data.mjs. Edit data/*.json and rebuild.\nwindow.DATA = ${JSON.stringify({ concert, roadmap, pieces, hanon, czerny, practice }, null, 1)};\n`;
writeFileSync(new URL("assets/data.js", root), out);
console.log(`assets/data.js: ${pieces.length} pieces, ${pieces.reduce((s, p) => s + p.sessions.length, 0)} sessions`);
